#!/bin/sh
# Local/dev ROOT admin credentials for the docker-compose.yml stack.
#
#   scripts/fetch-credentials.sh              Print credentials (generates secrets/local.env on first run)
#   scripts/fetch-credentials.sh --sync       Set adam's password in the running stack to the stored one
#   scripts/fetch-credentials.sh --rotate     Generate a new password, store it and sync it
#   scripts/fetch-credentials.sh --from-logs  Print the random password the seed logged (no stored file)
#
# The password lives in secrets/local.env (gitignored, mode 600), which
# docker-compose.yml passes to the API as BOOTSTRAP_ROOT_PASSWORD. The seed only
# uses it when it creates adam, so an existing database needs --sync once.
# Never use this for production: docker-compose.prod.yml takes its own secret.
set -eu

cd "$(dirname "$0")/.."

ENV_FILE=secrets/local.env
USERNAME=adam
API_URL=http://localhost:8001
WEB_URL=http://localhost:8082
MAILPIT_URL=http://localhost:8025

compose() {
    docker compose -f docker-compose.yml "$@"
}

die() {
    echo "error: $*" >&2
    exit 1
}

usage() {
    sed -n '2,7s/^# \{0,1\}//p' "$0"
}

# Upper, lower, digit and symbol are always present to satisfy the API's
# password policy; '$' and '&' are left out so the value is safe in env files.
generate_password() {
    random=$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 24)
    upper=$(LC_ALL=C tr -dc '[:upper:]' </dev/urandom | head -c 1)
    lower=$(LC_ALL=C tr -dc '[:lower:]' </dev/urandom | head -c 1)
    digit=$(LC_ALL=C tr -dc '0-9' </dev/urandom | head -c 1)
    symbol=$(LC_ALL=C tr -dc '@#%^+=!' </dev/urandom | head -c 1)
    printf '%s%s%s%s%s' "$random" "$upper" "$lower" "$digit" "$symbol"
}

write_env_file() {
    mkdir -p secrets
    old_umask=$(umask)
    umask 077
    {
        echo "# Local/dev only. Generated by scripts/fetch-credentials.sh; do not commit."
        # Single quotes: compose reads the value literally.
        printf "BOOTSTRAP_ROOT_PASSWORD='%s'\n" "$1"
    } >"$ENV_FILE.tmp"
    mv "$ENV_FILE.tmp" "$ENV_FILE"
    umask "$old_umask"
}

read_password() {
    sed -n "s/^BOOTSTRAP_ROOT_PASSWORD=//p" "$ENV_FILE" | tail -n 1 | sed "s/^'\(.*\)'$/\1/; s/^\"\(.*\)\"$/\1/"
}

api_running() {
    compose ps --status running --services 2>/dev/null | grep -qx api
}

refuse_production() {
    if api_running && [ "$(compose exec -T api printenv ENVIRONMENT 2>/dev/null || true)" = "production" ]; then
        die "the api container runs with ENVIRONMENT=production; this script is for local/dev only"
    fi
}

sync_password() {
    api_running || die "the api container is not running; start it with: docker compose up -d"
    # The password goes over stdin, never on a command line.
    printf '%s\n' "$1" | compose exec -T api python -m app.cli reset-password "$USERNAME"
}

# One sign-in attempt so a stale stored password is caught early.
check_login() {
    api_running || return 0
    command -v curl >/dev/null 2>&1 || return 0
    status=$(printf '%s' "$1" | curl -s -o /dev/null -w '%{http_code}' -m 10 -X POST "$API_URL/admin/login" \
        --data-urlencode "username=$USERNAME" --data-urlencode "password@-" || true)
    case "$status" in
        200) echo "Check:    signed in to $API_URL as $USERNAME" ;;
        401) echo "Check:    the stored password does not match this database; run: scripts/fetch-credentials.sh --sync" ;;
        *) echo "Check:    could not verify sign-in (HTTP $status)" ;;
    esac
}

print_credentials() {
    echo "Genesis local credentials"
    echo "  Admin console: $WEB_URL/admin/login"
    echo "  Username:      $USERNAME"
    echo "  Password:      $1"
    echo
    echo "  Web app:       $WEB_URL"
    echo "  API docs:      $API_URL/docs"
    echo "  Mailpit:       $MAILPIT_URL"
    echo
}

ensure_password() {
    if [ ! -f "$ENV_FILE" ]; then
        write_env_file "$(generate_password)"
        echo "Generated a new ROOT password in $ENV_FILE." >&2
        if api_running; then
            echo "The running database may already have adam; run --sync to apply it." >&2
        fi
    fi
    password=$(read_password)
    [ -n "$password" ] || die "$ENV_FILE has no BOOTSTRAP_ROOT_PASSWORD; delete it and run again"
}

case "${1:-}" in
    "")
        refuse_production
        ensure_password
        print_credentials "$password"
        check_login "$password"
        ;;
    --sync)
        refuse_production
        ensure_password
        sync_password "$password"
        print_credentials "$password"
        check_login "$password"
        ;;
    --rotate)
        refuse_production
        api_running || die "the api container is not running; start it with: docker compose up -d"
        password=$(generate_password)
        sync_password "$password"
        # Stored only after the database accepted it.
        write_env_file "$password"
        print_credentials "$password"
        check_login "$password"
        ;;
    --from-logs)
        refuse_production
        password=$(compose logs --no-color api 2>/dev/null | sed -n 's/.*Password: //p' | grep -v '^supplied via' | tail -n 1)
        [ -n "$password" ] || die "no seeded password in the api logs (logs rotated, or adam was seeded with $ENV_FILE)"
        print_credentials "$password"
        ;;
    -h|--help)
        usage
        ;;
    *)
        usage >&2
        exit 1
        ;;
esac
